import { defineConfig, type Plugin } from "vite";
import { readdirSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";

/** Names this build: the time it was made, and the commit in CI. The game shows "updated" when it changes. */
const BUILD = `${new Date().toISOString().slice(0, 16).replace(/[-:T]/g, "")}${process.env.GITHUB_SHA ? `-${process.env.GITHUB_SHA.slice(0, 7)}` : ""}`;

/** After the build: dist/version.json (what the game checks to see if it is out of date) and dist/sw.js, the service
    worker that keeps every file of this build for offline play and always asks the network first for the page, so
    starting the game online loads the newest build (src/app/update.ts). */
function offline(): Plugin {
  let outDir = "dist";
  return {
    name: "tac-tics-offline",
    apply: "build",
    configResolved(c) { outDir = c.build.outDir; },
    closeBundle() {
      const files: string[] = [];
      const walk = (dir: string) => {
        for (const f of readdirSync(dir)) {
          const p = join(dir, f);
          if (statSync(p).isDirectory()) walk(p);
          else files.push(relative(outDir, p).split("\\").join("/"));
        }
      };
      walk(outDir);
      const keep = files.filter((f) => f !== "sw.js" && f !== "version.json" && !f.endsWith(".map"));
      writeFileSync(join(outDir, "version.json"), JSON.stringify({ build: BUILD }));
      writeFileSync(join(outDir, "sw.js"), SW.replaceAll("__BUILD__", BUILD).replace("__FILES__", JSON.stringify(["./", ...keep])));
    },
  };
}

const SW = `/* Generated by vite.config.ts: keeps build __BUILD__ for offline play. */
const CACHE = "tac-tics-__BUILD__";
const FILES = __FILES__;
self.addEventListener("install", (e) => {
  // Every file of this build, so the whole game works offline; a file that fails is fetched again later.
  e.waitUntil(caches.open(CACHE).then((c) => Promise.all(FILES.map((f) => c.add(f).catch(() => {})))).then(() => self.skipWaiting()));
});
self.addEventListener("activate", (e) => {
  e.waitUntil(caches.keys().then((keys) => Promise.all(keys.filter((k) => k.startsWith("tac-tics-") && k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()));
});
self.addEventListener("fetch", (e) => {
  const req = e.request;
  if (req.method !== "GET" || new URL(req.url).origin !== location.origin) return;
  const page = req.mode === "navigate" || req.url.endsWith("/version.json");
  if (page) {
    // The page and the version: the network first (that is the update), the saved copy when offline.
    e.respondWith(fetch(req, { cache: "no-store" }).then((r) => {
      if (r.ok && req.mode === "navigate") { const copy = r.clone(); caches.open(CACHE).then((c) => c.put("./", copy)); }
      return r;
    }).catch(() => caches.match(req.mode === "navigate" ? "./" : req, { ignoreSearch: true, ignoreVary: true }).then((r) => r || Response.error())));
    return;
  }
  // Everything else is named by its content (Vite hashes) or never changes: the saved copy first.
  e.respondWith(caches.match(req, { ignoreSearch: true, ignoreVary: true }).then((hit) => hit || fetch(req).then((r) => {
    if (r.ok) { const copy = r.clone(); caches.open(CACHE).then((c) => c.put(req, copy)); }
    return r;
  })));
});
`;

// base "./" keeps every asset path relative, so the same build works on GitHub Pages (served under /tac-tics/)
// and inside the phone app, which opens the Pages site (capacitor.config.json).
export default defineConfig({
  base: "./",
  build: { target: "es2022" },
  define: { __BUILD__: JSON.stringify(BUILD) },
  plugins: [offline()],
});
