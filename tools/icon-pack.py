#!/usr/bin/env python3
"""Packs the menu icons taken from "496 pixel art icons for medieval/fantasy RPG" by Henrique Lazarini (7Soul1),
CC0, https://opengameart.org/content/496-pixel-art-icons-for-medievalfantasy-rpg (see CREDITS.md).

  python3 tools/icon-pack.py

Downloads the pack's zip (or reads 496_RPG_icons.zip / its folder given as the first argument), keeps only the icons
named in USED, and writes them in a row of 34x34 cells to public/art/ui/icons.png, plus src/ui/pack.ts with each
icon's cell. The menus show these (src/ui/icons.ts packUrl); the battle board keeps the small hand-drawn 16x16 icons,
which read better at board size. To use another icon from the pack, add its file name to USED and run this again."""
import io
