def load(src):
    if src and os.path.isdir(src):
        return {f[:-4]: Image.open(os.path.join(src, f)).convert("RGBA") for f in os.listdir(src) if f.endswith(".png")}
    data = open(src, "rb").read() if src else urllib.request.urlopen(URL).read()
    out = {}
    with zipfile.ZipFile(io.BytesIO(data)) as z:
        for n in z.namelist():
            if n.endswith(".png"):
                out[os.path.basename(n)[:-4]] = Image.open(io.BytesIO(z.read(n))).convert("RGBA")
    return out


def main():
    icons = load(sys.argv[1] if len(sys.argv) > 1 else None)
    missing = [n for n in USED if n not in icons]
    if missing:
        sys.exit(f"not in the pack: {missing}")
    sheet = Image.new("RGBA", (CELL * len(USED), CELL), (0, 0, 0, 0))
    for i, n in enumerate(USED):
        im = icons[n]
        assert im.size == (CELL, CELL), (n, im.size)
        sheet.paste(im, (i * CELL, 0))
    os.makedirs(os.path.join(ROOT, "public", "art", "ui"), exist_ok=True)
    sheet.save(os.path.join(ROOT, "public", "art", "ui", "icons.png"), optimize=True)
    with open(os.path.join(ROOT, "src", "ui", "pack.ts"), "w") as f:
        f.write("/* Generated by tools/icon-pack.py: the cell of each icon in public/art/ui/icons.png (34x34 cells in one row).\n")
        f.write("   Icons from \"496 pixel art icons for medieval/fantasy RPG\" by Henrique Lazarini (7Soul1), CC0. */\n")
        f.write("export const PACK_CELL = 34;\n")
        f.write("export const PACK = {\n")
        for i, n in enumerate(USED):
            f.write(f"  {n}: {i},\n")
        f.write("} as const;\n")
        f.write("export type PackIcon = keyof typeof PACK;\n")
    print(f"packed {len(USED)} icons")


if __name__ == "__main__":
    main()
